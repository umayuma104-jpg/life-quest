  const DRAW_ORDER = ['legs', 'feet', 'chest', 'head', 'shield', 'sword'];
  function rectsOf(rows, pal) {
    let r = '';
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        const ch = row[x];
        if (!pal[ch]) { x++; continue; }
        let n = 1;
        while (row[x + n] === ch) n++;
        r += `<rect x="${x}" y="${y}" width="${n}" height="1" fill="${pal[ch]}"/>`;
        x += n;
      }
    });
    return r;
  }
